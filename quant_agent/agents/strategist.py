    async def _calculate_position_size(
        self, signal: TradingSignal, capital: float, atr: float | None = None
    ) -> dict[str, Any]:
        """Calculate optimal position size based on risk."""
        if signal.entry_price is None or signal.stop_loss is None:
            return {"error": "Cannot calculate position size without entry and stop loss"}

        risk_per_share = abs(signal.entry_price - signal.stop_loss)
        max_risk = capital * 0.02  # 2% risk per trade

        # Calculate shares based on risk
        shares_by_risk = max_risk / risk_per_share if risk_per_share > 0 else 0

        # Calculate shares based on position limit
        max_position_value = capital * self.MAX_POSITION_PCT
        shares_by_limit = max_position_value / signal.entry_price

        # Use the smaller of the two
        shares = min(shares_by_risk, shares_by_limit)
        position_value = shares * signal.entry_price

        return {
            "symbol": signal.symbol,
            "shares": int(shares),
            "position_value": position_value,
            "position_pct": position_value / capital,
            "risk_amount": shares * risk_per_share,
            "risk_pct": (shares * risk_per_share) / capital,
            "entry_price": signal.entry_price,
            "stop_loss": signal.stop_loss,
        }
